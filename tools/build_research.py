"""Publish the research write-ups as real, crawlable HTML pages under /research.

Why this exists
---------------
The out-of-sample validation reports were only ever Markdown files inside the
engine repository. They are the most substantive, most defensible content the
project has - the only pages that document *how* the modulator was tested rather
than asserting that it works - and none of it was reachable from the web. That
is content a search engine cannot rank and a reader cannot check.

Rather than hand-transcribing tables of 20 baskets into HTML (where a single
mistyped digit turns published evidence into a false claim), this script reads
the Markdown verbatim from _research/ and renders it. The numbers on the site
are therefore the numbers in the source, by construction.

_research/ is the Jekyll-excluded source directory, same convention as _src/:
the Markdown never gets served, only the generated pages under research/.

Refreshing the content: re-copy the Markdown from the engine repo into
_research/ and re-run this script. Do not edit research/*.html by hand.

Usage
-----
    python tools/build_research.py            # write research/*.html
    python tools/build_research.py --check    # verify only, exit 1 if stale
"""
