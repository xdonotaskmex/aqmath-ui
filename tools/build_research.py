def asset_stamp():
    """Reuse whatever stamp tools/stamp_version.py last wrote, so these pages
    never point at a stylesheet version that does not exist."""
    body = (ROOT / "terms.html").read_text(encoding="utf-8")
    m = re.search(r'href="/styles\.min\.css\?v=([\w]+)"', body)
    if not m:
        raise SystemExit("cannot read current asset stamp from terms.html")
    return m.group(1)


def alternates(path):
    links = []
    for group in TRANSLATION_SETS:
        if path not in group:
            continue
        for other in group:
            doc = next(d for d in DOCS if d["path"] == other)
            links.append(f'<link rel="alternate" hreflang="{doc["lang"]}" '
                         f'href="{SITE}{other}">')
        links.append(f'<link rel="alternate" hreflang="x-default" href="{SITE}{group[0]}">')
    return links


