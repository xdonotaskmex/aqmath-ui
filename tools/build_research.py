CODE_RE = re.compile(r"`([^`]+)`")
IMG_RE = re.compile(r"!\[([^\]]*)\]\(([^)]+)\)")
LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
BOLD_RE = re.compile(r"\*\*(.+?)\*\*")
ITALIC_RE = re.compile(r"\*([^*]+)\*")
TABLE_RULE_RE = re.compile(r"^\|[\s:|-]+\|$")


def rewrite_target(target):
    for old, new in REWRITE.items():
        if target.startswith(old):
            return new + target[len(old):]
        if target == old:
            return new
    return target


def svg_box(url):
    """Intrinsic width/height so the chart does not shift the page while loading."""
    path = ROOT / url.lstrip("/")
    if not path.exists():
        raise SystemExit(f"referenced asset missing: {url}")
    head = path.read_text(encoding="utf-8")[:400]
    w = re.search(r'\bwidth="(\d+)"', head)
    h = re.search(r'\bheight="(\d+)"', head)
    if not (w and h):
        raise SystemExit(f"cannot read intrinsic size of {url}")
    return w.group(1), h.group(1)


def inline(text):
    """Inline Markdown -> HTML. Escapes first, so source text can never inject markup."""
    codes = []

    def stash(m):
        codes.append(htmllib.escape(m.group(1)))
        return f"\x00{len(codes) - 1}\x00"

    text = CODE_RE.sub(stash, text)
    text = htmllib.escape(text)
    text = BOLD_RE.sub(r"<strong>\1</strong>", text)
    text = ITALIC_RE.sub(r"<em>\1</em>", text)
    text = LINK_RE.sub(
        lambda m: f'<a href="{rewrite_target(m.group(2))}">{m.group(1)}</a>', text)
    text = re.sub(r"\x00(\d+)\x00", lambda m: f"<code>{codes[int(m.group(1))]}</code>", text)
    return text


def render_table(rows):
    align_row = rows[1]
    aligns = []
    for cell in [c.strip() for c in align_row.strip("|").split("|")]:
        if cell.endswith(":") and cell.startswith(":"):
            aligns.append("center")
        elif cell.endswith(":"):
            aligns.append("right")
        else:
            aligns.append("left")

    def cells(row):
        return [c.strip() for c in row.strip().strip("|").split("|")]

    out = ['<div class="rs-tablewrap">', "<table>", "<thead><tr>"]
    for i, cell in enumerate(cells(rows[0])):
        a = aligns[i] if i < len(aligns) else "left"
        out.append(f'<th style="text-align:{a}">{inline(cell)}</th>')
    out.append("</tr></thead>")
    out.append("<tbody>")
    for row in rows[2:]:
        out.append("<tr>")
        for i, cell in enumerate(cells(row)):
            a = aligns[i] if i < len(aligns) else "left"
            out.append(f'<td style="text-align:{a}">{inline(cell)}</td>')
        out.append("</tr>")
    out.append("</tbody></table></div>")
    return "\n".join(out)


def render_paragraph(lines):
    if len(lines) > 1 and all(l.startswith("**") for l in lines):
        # A metadata block (Date:/Engine:/Status:) - one fact per line, as written.
        return "<p>" + "<br>\n".join(inline(l) for l in lines) + "</p>"
    return "<p>" + inline(" ".join(lines)) + "</p>"


def markdown_to_html(md):
    """Render the Markdown subset these reports actually use. Not a general parser:
    it fails loudly on anything it does not recognise rather than dropping it."""
    lines = md.replace("\r\n", "\n").split("\n")
    out = []
    para = []
    items = []
    i = 0

    def flush():
        if para:
            out.append(render_paragraph(list(para)))
            para.clear()
        if items:
            out.append("<ul>" + "".join(f"<li>{inline(x)}</li>" for x in items) + "</ul>")
            items.clear()

    while i < len(lines):
        raw = lines[i]
        line = raw.strip()

        if not line:
            flush()
            i += 1
            continue

        if line == "---":
            flush()
            out.append("<hr>")
            i += 1
            continue

        m = re.match(r"^(#{1,4})\s+(.*)$", line)
        if m:
            flush()
            lvl = len(m.group(1))
            out.append(f"<h{lvl}>{inline(m.group(2))}</h{lvl}>")
            i += 1
            continue

        if line.startswith("> "):
            flush()
            out.append(f"<blockquote>{inline(line[2:])}</blockquote>")
            i += 1
            continue

        m = IMG_RE.fullmatch(line)
        if m:
            flush()
            url = rewrite_target(m.group(2))
            w, h = svg_box(url)
            out.append(f'<figure class="rs-fig"><img src="{url}" alt="{htmllib.escape(m.group(1))}" '
                       f'width="{w}" height="{h}" loading="lazy" decoding="async"></figure>')
            i += 1
            continue

        if line.startswith("|"):
            flush()
            if i + 1 >= len(lines) or not TABLE_RULE_RE.match(lines[i + 1].strip()):
                raise SystemExit(f"table without an alignment row at line {i + 1}: {line}")
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(lines[i].strip())
                i += 1
            out.append(render_table(rows))
            continue

        if line.startswith("- "):
            if para:
                flush()
            items.append(line[2:])
            i += 1
            continue

        if items and raw.startswith("  "):
            # Continuation of the previous list item.
            items[-1] = items[-1] + " " + line
            i += 1
            continue

        para.append(line)
        i += 1

    flush()
    return "\n".join(out)


