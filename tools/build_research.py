def render_doc(doc):
    md = (SRC_DIR / doc["src"]).read_text(encoding="utf-8")
    ui = UI[doc["lang"]]
    other = next((d for d in DOCS
                  for g in TRANSLATION_SETS
                  if doc["path"] in g and d["path"] in g and d["path"] != doc["path"]), None)

    body_md = markdown_to_html(md)
    # The source's own cross-language line points at a repo file; the header link
    # below is the real one, so drop the duplicate.
    body_md = re.sub(r"<blockquote>.*?</blockquote>\s*", "", body_md, count=1, flags=re.S)

    nav = [f'<p class="rs-nav"><a href="/research">{ui["backToHub"]}</a>']
    if other:
        nav.append(f'<span class="sep">|</span>{ui["alsoIn"]} '
                   f'<a href="{other["path"]}" hreflang="{other["lang"]}">{doc["altLabel"]}</a>')
    nav.append("</p>")

    # The document title has to be the first heading a reader and a crawler meet,
    # so lift it out of the rendered body and put the notices underneath it.
    m = re.match(r"\s*(<h1>.*?</h1>)\s*", body_md, flags=re.S)
    if not m:
        raise SystemExit(f"{doc['src']}: expected the document to open with a level-1 heading")
    heading, rest = m.group(1), body_md[m.end():]

    body = "\n".join([
        "".join(nav),
        heading,
        f'<p class="legal-updated">{ui["published"]}: {doc["published"]}</p>',
        f'<p class="sim-notice">{SIM_NOTICE[doc["lang"]]}</p>',
        rest,
    ])
    return shell(doc["lang"], doc["htmlLang"], doc["title"], doc["description"],
                 doc["path"], body)


def render_hub():
    ui = UI["en"]
    cards = []
    for doc in DOCS:
        if doc["lang"] != "en":
            continue
        other = next((d for d in DOCS
                      for g in TRANSLATION_SETS
                      if doc["path"] in g and d["path"] in g and d["path"] != doc["path"]), None)
        alt = (f' <span class="rs-card-alt">&middot; <a href="{other["path"]}" '
               f'hreflang="{other["lang"]}">{doc["altLabel"]}</a></span>') if other else ""
        cards.append(
            f'<li class="rs-card"><a href="{doc["path"]}">{doc["shortTitle"]}</a>'
            f'<span class="rs-card-date">{doc["published"]}</span>{alt}'
            f'<p>{doc["description"]}</p></li>')
    body = "\n".join([
        f'<div class="rs-kicker">{ui["hubKicker"]}</div>',
        f'<h1>{ui["hubTitle"]}</h1>',
        f'<p>{ui["hubIntro"]}</p>',
        '<ul class="rs-list">',
        *cards,
        "</ul>",
        '<p>Interactive version: run the same engine on your own price data at '
        '<a href="/backtest">/backtest</a>, or see the live paper-trading log at '
        '<a href="/results">/results</a>.</p>',
    ])
    return shell(
        "en", "en", "Research &amp; Validation &mdash; AQMath",
        "Published out-of-sample validation reports for the AQMath Deleverage Modulator: "
        "test methodology, per-basket results, stress cases and caveats.",
        "/research", body)


def build():
    pages = {"index.html": render_hub()}
    for doc in DOCS:
        pages[doc["out"]] = render_doc(doc)
    return pages


def main(check_only=False):
    if not SRC_DIR.exists():
        raise SystemExit(f"missing source directory: {SRC_DIR}")
    pages = build()

    stale = []
    for name, text in pages.items():
        path = OUT_DIR / name
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(name)

    if check_only:
        if stale:
            print("research pages STALE - re-run tools/build_research.py:")
            for n in stale:
                print("  research/" + n)
            return 1
        print(f"research pages OK - {len(pages)} in sync with _research/")
        return 0

    OUT_DIR.mkdir(exist_ok=True)
    for name, text in pages.items():
        (OUT_DIR / name).write_text(text, encoding="utf-8")
        h1 = len(re.findall(r"<h1\b", text))
        if h1 != 1:
            raise SystemExit(f"research/{name}: expected exactly 1 <h1>, found {h1}")
        print(f"  research/{name:28s} {len(text):>7,}B h1=1")
    print(f"wrote {len(pages)} research pages from {SRC_DIR.name}/")
    return 0


if __name__ == "__main__":
    sys.exit(main(check_only="--check" in sys.argv))
